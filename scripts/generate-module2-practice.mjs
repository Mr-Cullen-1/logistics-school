import assert from 'node:assert/strict';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { module2Practice } from './module2-practice-content.mjs';

const style = await readFile(new URL('./module2-practice-theme.css', import.meta.url), 'utf8');
assert.equal(Object.keys(module2Practice).length, 8);
let count = 0;
for (const [code, tasks] of Object.entries(module2Practice)) {
  assert.equal(tasks.length, 10, code);
  assert.equal(tasks[9].kind, 'SCENE', code);
  assert.ok(new Set(tasks.map(task => task.kind)).size >= 5, code);
  assert.ok(tasks.some(task => task.kind === 'FIX'), code);
  assert.ok(tasks.filter(task => ['READ-MC', 'READ-TYPE'].includes(task.kind)).length >= 2, code);
  const directory = new URL(`../jsx-lessons/practice/${code}/`, import.meta.url);
  await mkdir(directory, { recursive: true });
  for (const [index, content] of tasks.entries()) {
    const seq = index + 1;
    const id = `${code}.p${String(seq).padStart(2, '0')}`;
    const task = { id, ...content };
    for (const field of ['title', 'instruction', 'questionText', 'hint', 'success']) assert.ok(task[field], `${id}: ${field}`);
    if (task.options) assert.ok(task.options[task.answer], id);
    if (task.steps) { assert.equal(task.steps.length, 3, id); for (const step of task.steps) assert.ok(step.options[step.answer], id); }
    if (task.fields) for (const field of task.fields) assert.ok(field.answers.length && field.answers.every(Boolean), id);
    if (task.pairs) assert.equal(new Set(task.pairs.map(pair => pair.right)).size, task.pairs.length, id);
    if (task.groups) { const items = task.groups.flatMap(group => group.items); assert.equal(new Set(items).size, items.length, id); }
    if (task.tokens) assert.deepEqual([...task.tokens].sort(), [...task.expected].sort(), id);
    const source = `// Generated by scripts/generate-module2-practice.mjs. Edit its content source instead.
import React, { useCallback, useState } from "react";
import { PracticeTask } from "@coliseum/kit";

export const meta = ${JSON.stringify({ type: 'practice', lessonCode: code, seq, mechanic: task.kind }, null, 2)};

const task = ${JSON.stringify(task, null, 2)};

const STYLE = ${JSON.stringify(style)};

function shuffled(items) {
  const copy = [...items];
  for (let index = copy.length - 1; index > 0; index--) {
    const other = Math.floor(Math.random() * (index + 1));
    [copy[index], copy[other]] = [copy[other], copy[index]];
  }
  return copy;
}
function mixChoices(value) {
  const correct = value.options[value.answer];
  const options = shuffled(value.options);
  return { ...value, options, answer: options.indexOf(correct) };
}
function prepare() {
  let definition = { ...task };
  if (task.options) definition = mixChoices(definition);
  if (task.steps) definition.steps = task.steps.map(mixChoices);
  if (task.tokens) definition.tokens = shuffled(task.tokens);
  // FORM uses the existing typed-fields renderer; public metadata stays FORM.
  if (task.kind === "FORM") definition.kind = "TYPE";
  return definition;
}

export default function Practice({ onSubmit, ...props }) {
  const [definition] = useState(prepare);
  const submit = useCallback(result => onSubmit?.({ ...result, meta: { ...result.meta, kind: task.kind } }), [onSubmit]);
  return <div className="m2-practice"><style>{STYLE}</style><PracticeTask {...props} definition={definition} onSubmit={submit} /></div>;
}
`;
    await writeFile(new URL(`${id}.jsx`, directory), source);
    count++;
  }
  await rm(new URL('.gitkeep', directory), { force: true });
}
console.log(`Created ${count} standalone Module 2 Practice JSX files.`);
